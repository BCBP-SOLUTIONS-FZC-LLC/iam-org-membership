// TestRegisterDocsRoutes_SwaggerDocJson_HitsDefaultBranch verifies that a
// GET /swagger/doc.json request falls through to the `default: stdSwagger(c)`
// branch in the /swagger/*any handler, bypassing both the index.css and the
// swagger-initializer.js special cases.
//
// The secHeaders middleware (registered before the switch) sets X-Frame-Options
// on every /swagger/* response. Its presence confirms the route was registered
// and the middleware chain ran — even when ginSwagger returns 404 in test mode
// because no swagger spec has been generated (docs are generated by `make swag`,
// which is not run in unit tests).
//
// Contrast: an unregistered path produces no X-Frame-Options header.
func TestRegisterDocsRoutes_SwaggerDocJson_HitsDefaultBranch(t *testing.T) {
	gin.SetMode(gin.TestMode)
	r := gin.New()
	cfg := RouterConfig{
		Docs: DocsConfig{
			Environment: "dev",
			Enabled:     true,
		},
	}
	registerDocsRoutes(r, cfg)

	// /swagger/doc.json — ends in neither /index.css nor /swagger-initializer.js,
	// so the switch default branch (stdSwagger) runs.
	w := httptest.NewRecorder()
	req, _ := http.NewRequestWithContext(
		context.Background(), http.MethodGet, "/swagger/doc.json", nil,
	)
	r.ServeHTTP(w, req)

	// secHeaders sets X-Frame-Options on every matched /swagger/* route.
	// Its presence proves the route was matched and the handler chain ran.
	assert.Equal(t, "DENY", w.Header().Get("X-Frame-Options"),
		"/swagger/doc.json must set X-Frame-Options, proving secHeaders + default branch ran")
	assert.NotEqual(t, http.StatusUnauthorized, w.Code,
		"/swagger/doc.json must not require auth in non-production")
}

