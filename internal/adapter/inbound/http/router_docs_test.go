// TestRegisterDocsRoutes_SwaggerDocJson_ProductionWithToken_BlocksUnauth
// verifies that the default stdSwagger branch is also protected by the
// production auth middleware: a request to /swagger/doc.json without the
// correct token returns 401, not 200.
func TestRegisterDocsRoutes_SwaggerDocJson_ProductionWithToken_BlocksUnauth(t *testing.T) {
	gin.SetMode(gin.TestMode)
	r := gin.New()
	cfg := RouterConfig{
		Docs: DocsConfig{
			Environment: "production",
			Enabled:     true,
			AuthToken:   "my-secret",
		},
	}
	registerDocsRoutes(r, cfg)

	w := httptest.NewRecorder()
	req, _ := http.NewRequestWithContext(
		context.Background(), http.MethodGet, "/swagger/doc.json", nil,
	)
	r.ServeHTTP(w, req)

	assert.Equal(t, http.StatusUnauthorized, w.Code,
		"production /swagger/doc.json without auth must return 401")
}

// TestRegisterDocsRoutes_SwaggerDocJson_ProductionWithToken_AllowsValidToken
// verifies that the correct Bearer token lets a /swagger/doc.json request pass
// the auth middleware and reach stdSwagger.  The X-Frame-Options header set by
// secHeaders confirms the full middleware chain ran (secHeaders → authMiddleware
// → handler switch → default branch).
func TestRegisterDocsRoutes_SwaggerDocJson_ProductionWithToken_AllowsValidToken(t *testing.T) {
	gin.SetMode(gin.TestMode)
	r := gin.New()
	cfg := RouterConfig{
		Docs: DocsConfig{
			Environment: "production",
			Enabled:     true,
			AuthToken:   "my-secret",
		},
	}
	registerDocsRoutes(r, cfg)

	w := httptest.NewRecorder()
	req, _ := http.NewRequestWithContext(
		context.Background(), http.MethodGet, "/swagger/doc.json", nil,
	)
	req.Header.Set("Authorization", "Bearer my-secret")
	r.ServeHTTP(w, req)

	// Auth passed; secHeaders set X-Frame-Options; stdSwagger ran.
	assert.NotEqual(t, http.StatusUnauthorized, w.Code,
		"valid token must pass production auth on /swagger/doc.json")
	assert.Equal(t, "DENY", w.Header().Get("X-Frame-Options"),
		"X-Frame-Options must be set, confirming secHeaders and the default branch ran")
}
